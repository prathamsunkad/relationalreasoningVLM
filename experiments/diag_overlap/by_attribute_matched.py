"""Per-attribute accuracy of each matched-data hybrid vs its equal-steps control on the 5,000 test puzzles.

Added Nov 25 for the peer-review question on counting gains. results/relational/test5000/report.md (analyze5k.py) has
the same breakdown only for the older runs (H11-H13); this covers the matched-data H15 (20%) and H16 (5%) pairs.

A puzzle counts once under every attribute it has a rule on (rules.json.gz: [object, attribute, relation] per rule).
Accuracy uses llm_pred (the VLM's answer). p = exact two-sided McNemar test on the discordant puzzles.

  python experiments/diag_overlap/by_attribute_matched.py results/relational/test5000 \
      > results/relational/test5000/by_attribute_matched.md
"""
import gzip
import json
import math
import sys
from pathlib import Path

PAIRS = [
    ('H15, matched 20%, LoRA after epoch 1, interleave', 'lf20e1_int', 'lf20e1_int_ctrl'),
    ('H15, matched 20%, LoRA after epoch 1, fusion', 'lf20e1_fuse', 'lf20e1_fuse_ctrl'),
    ('H15, matched 20%, LoRA after epoch 4, interleave', 'lf20e4_int', 'lf20e4_int_ctrl'),
    ('H15, matched 20%, LoRA after epoch 4, fusion', 'lf20e4_fuse', 'lf20e4_fuse_ctrl'),
    ('H16, matched 5%, LoRA after epoch 1, interleave', 'lf5e1_int', 'lf5e1_int_ctrl'),
    ('H16, matched 5%, LoRA after epoch 2, interleave', 'lf5e2_int', 'lf5e2_int_ctrl'),
    ('H13, matched 5%, full 5% LoRA, interleave', 'c60_lf_int', 'lf_int_ctrl'),
    ('H13, matched 5%, full 5% LoRA, fusion', 'c60_lf_fuse', 'lf_fuse_ctrl'),
]
ATTRS = ['number', 'position', 'type', 'size', 'color']


def load(d, name):
    return json.load(gzip.open(Path(d) / f'{name}.json.gz'))


def correct(d, name):
    return {r['id']: int(r['llm_pred'] == r['label']) for r in load(d, name)['records']}


def mcnemar(b, c):
    n = b + c
    if n == 0:
        return 1.0
    return min(1.0, 2 * sum(math.comb(n, i) for i in range(min(b, c) + 1)) / 2 ** n)


def main(d):
    rules = load(d, 'rules')
    print('# By attribute: matched-data hybrids vs equal-steps controls (test5000)\n')
    print('Generated by `experiments/diag_overlap/by_attribute_matched.py`. A puzzle counts once under every attribute it '
          'has a rule on. "number" = counting rules. p = exact McNemar on discordant puzzles. All shapes in these test '
          'puzzles also occur in training (PGM neutral split), so this is in-distribution only.\n')
    for title, h, c in PAIRS:
        H, C = correct(d, h), correct(d, c)
        ids = [i for i in H if i in C]
        print(f'## {title}: `{h}` vs `{c}`\n')
        print(f'All {len(ids)} puzzles: {100 * sum(H[i] for i in ids) / len(ids):.1f}% vs '
              f'{100 * sum(C[i] for i in ids) / len(ids):.1f}%\n')
        print('| Attribute | n | Hybrid | Control | Gap | p |')
        print('|---|---|---|---|---|---|')
        for a in ATTRS:
            s = [i for i in ids if any(r[1] == a for r in rules[i])]
            hb, cb = sum(H[i] for i in s) / len(s), sum(C[i] for i in s) / len(s)
            b = sum(1 for i in s if H[i] and not C[i])
            k = sum(1 for i in s if C[i] and not H[i])
            print(f'| {a} | {len(s)} | {100 * hb:.1f}% | {100 * cb:.1f}% | {100 * (hb - cb):+.1f} | {mcnemar(b, k):.1g} |')
        print()


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else 'results/relational/test5000')
